#!/usr/bin/env python3
"""Builds prompts/01_sorani.md and prompts/02_kurmanji.md from script/scenes.json. Run: python3 tools/build.py"""
import json, pathlib
R = pathlib.Path(__file__).resolve().parent.parent
D = json.loads((R / "script/scenes.json").read_text(encoding="utf-8"))
L = {"ckb": ("Kurdish Sorani", "01_sorani.md", "RTL, Arabic script", "Speda Bold (fallback Noto Sans Arabic Bold)", 2.2, "Dween - دوین"),
     "kmr": ("Kurdish Kurmanji", "02_kurmanji.md", "LTR, Latin (Hawar) script", "Montserrat Bold (fallback Noto Sans Bold)", 2.3, "Dwîn - Kurmancî")}

SPEC = """## 3. Technical specification
- **Format:** master 16:9, 1920×1080, 24 fps; also export a 9:16 1080×1920 version (reframe shots; keep text inside the central 1080×1350 area). H.264 `yuv420p`, AAC 48 kHz, −14 LUFS, true peak ≤ −1 dBTP.
- **Vox look:** a clean newsroom-paper world: off-white paper `#F2EEE6`, ink `#1B1B1B`, oil-black `#0B0B0B` for the slick, sea blue `#2E6F8E`, Dwin gold `#C9A45C`, alert red `#B3261E` (only for attacks and closures). Photos as cut-outs with soft shadows, 2.5D parallax pushes of 3–6%, ink circles and arrows that draw on, gold highlighter behind key numbers, film grain 5%.
- **Maps:** vector map of the UAE coast and the Strait of Hormuz (Natural Earth). Pins drop for Umm Al Quwain, Sharjah (Al Hamriyah), Ajman, Ras Al Khaimah; the slick is an animated black shape that spreads; the 25 km distance is a dashed line with a label.
- **Data:** numbers count up on screen (160 km², 28, 11, 3.5%); bars drawn to scale; every number shows its source in small text under it.
- **Typography:** {font}; {dir}; Western digits; titles 90 px, labels 54 px, source lines 22 px.
- **Narration:** one calm, clear male or female news narrator in {lang}, about {wps} words per second; 48 kHz/24-bit WAV; read the narration exactly as written.
- **Music & sound:** tense, minimal news underscore (low synth pulse, 90–100 BPM, no vocals), −20 dB under narration. SFX: map whoosh, pin pops, counter ticks, waves, seagulls far away, a low boom on the attack numbers. No explosion sounds.
- **Subtitles:** burn in subtitles of the narration for the 9:16 version (cream text on a 60% black box, bottom, max 2 lines).
- **Labels:** AI-generated images carry a small "illustration" label (**{ill}**); real photos and satellite images carry their credit (e.g. "Copernicus Sentinel data 2026").
- **Branding:** Dwin logo top-left, 70% opacity; Dwin end card (logo + {chan}). No sources slide at the end.
"""

RULES = """## 2. Editorial rules
1. Use the narration and on-screen text **exactly as written**. Do not translate, shorten or add.
2. This is news about an ongoing war: stay factual and neutral. The tanker was hit by an **unknown projectile** (Reuters); do not blame any country on screen.
3. Every number shows its source on screen in small text (UAE ministry, Reuters, Copernicus, Washington Institute, Reuters/IMO/MarineTraffic).
4. No dead animals, injured people or explosions on screen. Damage is shown with maps, satellite images and calm footage.
5. The ministry's health statement (the smell is not a health risk) must stay in the video.
"""

def block(s, lang):
    out = [f"### {s['id']} · {s['start']}–{s['end']} s · {s['kind']}", "", "**Narration** — read exactly:", "", "```text", s["vo"][lang], "```",
           "**On-screen text** — copy exactly:", "", "```text", *s["ost"][lang], "```",
           f"- Meaning (English, editor only): {s['vo_en']}"]
    out += [f"- Visual: {v}" for v in s["visual"]]
    out.append("- Images: " + ", ".join(f"`assets/images/{i.format(lang=lang)}`" for i in s["images"]) if s["images"] else "- Images: drawn graphics only")
    out += [f"- Sound: {s['sfx']}", f"- Source: {s['source']}", ""]
    return "\n".join(out)

def build():
    for lang, (name, fn, dr, font, wps, chan) in L.items():
        t = 0.0
        for s in D["scenes"]:
            d = round(max(len(s["vo"][lang].split()) / wps + 0.8, 3.0), 1) if s["vo"][lang] else 3.0
            s["start"], s["end"] = round(t, 1), round(t + d, 1); t += d
        head = f"""# Dwin Vox-style news explainer — {name} — UAE oil spill (October 2026)

> Generated by `tools/build.py` from `script/scenes.json`. Images needed: `IMAGES.md`.

**Title on screen:** {D['title'][lang]}
**Estimated length:** {t:.0f} s (~{t/60:.1f} min), {len(D['scenes'])} scenes. Final timing follows the recorded narration.

## 1. Role and goal
You are Dwin's senior editor and motion designer. Make a short **Vox-style news explainer with narration** in **{name}**: how the war's attacks on shipping turned into an oil slick on the beaches of the UAE, how big it is, what was closed, and what the numbers say about the war at sea. The prompt is in English; **only the narration and on-screen text are in {name}**.

"""
        body = [head, RULES, SPEC.format(font=font, dir=dr, lang=name, wps=wps, ill=D["label_illustration"][lang], chan=chan),
                f"## 4. Scene-by-scene script ({name})\n"]
        body += [block(s, lang) for s in D["scenes"]]
        body.append(f"## 5. Post description ({name})\n\n```text\n{D['caption'][lang]}\n```\n")
        body.append("## 6. Facts and corrections\n" + "\n".join(f"- {f}" for f in D["facts"]) + "\n")
        (R / "prompts").mkdir(exist_ok=True)
        (R / "prompts" / fn).write_text("\n".join(body), encoding="utf-8")
        print(fn, f"{t:.0f}s")

build()
